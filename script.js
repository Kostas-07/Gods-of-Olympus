let godIndex = 0;
let questionIndex = 0;
let correctCount = 0;
let answered = false;

const $ = (id) => document.getElementById(id);
const game = $("game"), result = $("result");

function renderQuestion() {
  const god = gods[godIndex];
  const q = god.questions[questionIndex];
  answered = false;
  $("levelLabel").textContent = `Θεός ${godIndex + 1} από 12`;
  $("scoreLabel").textContent = `Ερώτηση ${questionIndex + 1} από 5`;
  $("progressBar").style.width = `${(questionIndex / 5) * 100}%`;
  $("godName").textContent = god.name;
  $("godDescription").textContent = god.desc;
  $("question").textContent = q[0];
  $("feedback").textContent = "";
  $("nextButton").disabled = true;
  $("nextButton").textContent = questionIndex === 4 ? "Ολοκλήρωση γύρου" : "Επόμενη ερώτηση";
  $("answers").innerHTML = "";
  q[1].forEach((answer, i) => {
    const button = document.createElement("button");
    button.className = "answer";
    button.textContent = `${String.fromCharCode(65 + i)}. ${answer}`;
    button.addEventListener("click", () => chooseAnswer(i, button));
    $("answers").appendChild(button);
  });
}

function chooseAnswer(selected, button) {
  if (answered) return;
  answered = true;
  const correct = gods[godIndex].questions[questionIndex][2];
  [...$("answers").children].forEach((el, i) => {
    el.disabled = true;
    if (i === correct) el.classList.add("correct");
  });
  if (selected === correct) {
    correctCount++;
    $("feedback").textContent = "Σωστά! Μπράβο!";
    $("feedback").style.color = "#4ade80";
  } else {
    button.classList.add("wrong");
    $("feedback").textContent = "Λάθος απάντηση. Ο γύρος απέτυχε.";
    $("feedback").style.color = "#fca5a5";
  }
  $("nextButton").disabled = false;
}

$("nextButton").addEventListener("click", () => {
  if (correctCount !== questionIndex + 1) {
    showResult(false);
    return;
  }
  if (questionIndex < 4) {
    questionIndex++;
    renderQuestion();
  } else {
    showResult(correctCount === 5);
  }
});

function showResult(success) {
  game.classList.add("hidden");
  result.classList.remove("hidden");
  $("retryButton").classList.toggle("hidden", success);
  $("continueButton").classList.toggle("hidden", !success || godIndex === gods.length - 1);
  $("restartButton").classList.toggle("hidden", !(success && godIndex === gods.length - 1));
  $("resultTitle").textContent = success ? (godIndex === gods.length - 1 ? "Κατέκτησες και τους 12 Θεούς!" : `Κατέκτησες τον ${gods[godIndex].name}!`) : "Δεν ξεκλείδωσες τον επόμενο θεό.";
  $("resultText").textContent = success ? (godIndex === gods.length - 1 ? "Συγχαρητήρια! Ολοκλήρωσες όλο το παιχνίδι με 60 σωστές απαντήσεις." : "Πέτυχες 5/5 σωστές απαντήσεις. Μπορείς να συνεχίσεις!") : `Έκανες ${correctCount}/5 σωστές απαντήσεις. Χρειάζεσαι 5/5. Δοκίμασε ξανά!`;
}

$("retryButton").addEventListener("click", () => startGod(godIndex));
$("continueButton").addEventListener("click", () => startGod(godIndex + 1));
$("restartButton").addEventListener("click", () => startGod(0));

function startGod(index) {
  godIndex = index;
  questionIndex = 0;
  correctCount = 0;
  result.classList.add("hidden");
  game.classList.remove("hidden");
  renderQuestion();
}

startGod(0);
